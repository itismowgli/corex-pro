#!/bin/bash
# lib/heartbeat.sh, CoreX Pro
# An alert from outside the machine when the machine stops.
#
# Everything that watches this box runs on this box. Uptime Kuma, the resource
# watchdog and the Telegram bot all stop when it does, so the one failure they
# cannot report is the whole machine being down. On 2026-11-07 and 2026-11-09
# the system disk hung, the recovery did not bring the machine back, and it
# stayed dark for 2.4 and 3.6 days because nothing anywhere noticed.
#
# The fix is a dead-man's switch: the box sends a request to a service outside
# the house once a minute, and that service raises the alarm when the requests
# stop. Any service that works that way will do (healthchecks.io has a free
# tier that sends to Telegram, and a second Uptime Kuma elsewhere has push
# monitors). CoreX only needs the URL.
#
# A beat is a claim that the machine is useful, not that it is powered. A hung
# system disk leaves the kernel answering pings for hours, so each beat first
# starts a process, writes to the system disk and asks Docker a question, and
# is not sent unless all three finish. When the disk hangs the check hangs
# with it, the beats stop, and silence is what raises the alarm. That is the
# reason this is a timer and not a daemon: the disk guard has to survive a
# dead disk, and this has to stop with one.

HEARTBEAT_CONF="${HEARTBEAT_CONF:-/etc/corex/heartbeat.conf}"
HEARTBEAT_BIN="${HEARTBEAT_BIN:-/usr/local/bin/corex-heartbeat.sh}"
HEARTBEAT_STATE="${HEARTBEAT_STATE:-/var/lib/corex/heartbeat.last}"

source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

# https only, and nothing a shell or a config parser could read as syntax.
# The URL is a capability: whoever holds it can keep the alarm quiet.
heartbeat_valid_url() {
    [[ "${1:-}" =~ ^https://[A-Za-z0-9._~:/?#@!\&=%+-]+$ ]]
}

heartbeat_url() {
    [[ -r "$HEARTBEAT_CONF" ]] || return 0
    sed -n 's/^HEARTBEAT_URL="\(.*\)"$/\1/p' "$HEARTBEAT_CONF" | tail -1
}

# The URL with its token removed, for anything that prints.
heartbeat_url_masked() {
    local url host
    url="$(heartbeat_url)"
    [[ -n "$url" ]] || return 0
    host="${url#https://}"
    echo "https://${host%%/*}/..."
}

_heartbeat_write_script() {
    install_script "$HEARTBEAT_BIN" 750 << 'HBEOF'
#!/bin/bash
# Generated by lib/heartbeat.sh. Sends one beat if the machine is useful.
set -u
CONF="${HEARTBEAT_CONF:-/etc/corex/heartbeat.conf}"
STATE="${HEARTBEAT_STATE:-/var/lib/corex/heartbeat.last}"
URL="$(sed -n 's/^HEARTBEAT_URL="\(.*\)"$/\1/p' "$CONF" 2>/dev/null | tail -1)"
[[ -n "$URL" ]] || exit 0

# Each of these waits on the system disk. None has a retry: a check that
# cannot finish must not beat, and the next run is a minute away.
PROBE="$(dirname "$STATE")/.heartbeat-probe"
timeout 20 sh -c 'echo "$$" > "$1" && sync "$1"' sh "$PROBE" || exit 1
if command -v docker >/dev/null 2>&1; then
    timeout 20 docker info --format '{{.ServerVersion}}' >/dev/null 2>&1 || exit 1
fi

# A generic client name. Nothing about this machine goes in the request.
if curl -fsS -m 15 --retry 2 -A "corex-heartbeat" -o /dev/null "$URL"; then
    date +%s > "$STATE"
else
    exit 1
fi
HBEOF
}

heartbeat_setup() {
    local url="${1:-}"
    if [[ -z "$url" ]]; then
        url="$(heartbeat_url)"
        [[ -n "$url" ]] || {
            log_warning "Give the check URL: sudo corex manage heartbeat setup https://..."
            return 1
        }
    fi
    heartbeat_valid_url "$url" || {
        log_warning "The URL has to start with https:// and hold no spaces or quotes"
        return 1
    }
    command -v curl >/dev/null 2>&1 || { log_warning "The heartbeat needs curl"; return 1; }

    mkdir -p "$(dirname "$HEARTBEAT_CONF")" "$(dirname "$HEARTBEAT_STATE")"
    install_script "$HEARTBEAT_CONF" 600 << HCEOF
# CoreX heartbeat. The URL is a secret: whoever has it can silence the alarm.
# Change with: sudo corex manage heartbeat setup <url>
HEARTBEAT_URL="${url}"
HCEOF
    _heartbeat_write_script

    cat > /etc/systemd/system/corex-heartbeat.service << HSEOF
[Unit]
Description=CoreX heartbeat (tells an outside service this machine is working)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=${HEARTBEAT_BIN}
# A beat that cannot finish is a beat that must not be sent. Without this a
# check stuck on a dead disk would hold the unit active and the timer would
# never start another, which is the right outcome reached by accident.
TimeoutStartSec=90
HSEOF
    cat > /etc/systemd/system/corex-heartbeat.timer << 'HTEOF'
[Unit]
Description=CoreX heartbeat, once a minute

[Timer]
OnBootSec=60s
OnUnitActiveSec=60s
AccuracySec=5s

[Install]
WantedBy=timers.target
HTEOF
    systemctl daemon-reload
    systemctl enable corex-heartbeat.timer >/dev/null 2>&1
    systemctl restart corex-heartbeat.timer
    log_success "Heartbeat installed, one beat a minute to $(heartbeat_url_masked)"
    heartbeat_test || true
    log_info "Set the check to expect a beat every 1 minute with a grace of 3 minutes."
}

# One beat now, reporting whether the outside service accepted it.
heartbeat_test() {
    [[ -n "$(heartbeat_url)" ]] || { log_warning "No heartbeat is configured"; return 1; }
    [[ -x "$HEARTBEAT_BIN" ]] || _heartbeat_write_script
    if "$HEARTBEAT_BIN"; then
        log_success "Beat sent and accepted"
    else
        log_warning "Beat not sent: the disk check, Docker or the request failed"
        return 1
    fi
}

heartbeat_disable() {
    systemctl disable --now corex-heartbeat.timer >/dev/null 2>&1 || true
    rm -f /etc/systemd/system/corex-heartbeat.timer /etc/systemd/system/corex-heartbeat.service
    systemctl daemon-reload 2>/dev/null || true
    rm -f "$HEARTBEAT_CONF" "$HEARTBEAT_BIN"
    log_success "Heartbeat removed. Pause or delete the check at the service too, or it will alert."
}

# Seconds since the last accepted beat, or nothing when there has been none.
heartbeat_age() {
    local last
    last="$(cat "$HEARTBEAT_STATE" 2>/dev/null)"
    [[ "$last" =~ ^[0-9]+$ ]] || return 0
    echo $(( $(date +%s) - last ))
}

heartbeat_status() {
    if [[ -z "$(heartbeat_url)" ]]; then
        log_warning "No heartbeat. Nothing outside this machine will notice if it stops."
        log_info "Create a check at a dead-man's-switch service, then:"
        log_info "  sudo corex manage heartbeat setup https://<the check's ping URL>"
        return 1
    fi
    log_info "Beating to $(heartbeat_url_masked)"
    systemctl is-active --quiet corex-heartbeat.timer 2>/dev/null \
        || log_warning "The timer is not running: sudo corex manage heartbeat setup"
    local age
    age="$(heartbeat_age)"
    if [[ -z "$age" ]]; then
        log_warning "No beat has been accepted yet: sudo corex manage heartbeat test"
        return 1
    elif (( age > 180 )); then
        log_warning "Last accepted beat was ${age}s ago. The outside check is alerting by now."
        return 1
    fi
    log_success "Last accepted beat ${age}s ago"
}
